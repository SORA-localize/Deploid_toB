/** camelCase field/roleキーをsnake_caseの列名断片へ（Payload/drizzleの列命名規則と一致させる）。 */
function toSnakeCase(value: string): string {
  return value.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

function imageAssetBackfillAssignments(jsonColumn: string, role: string): string[] {
  const prefix = `${jsonColumn}_${toSnakeCase(role)}`;
  const rolePath = `"${jsonColumn}"->'${role}'`;
  return [
    `"${prefix}_src" = ${rolePath}->>'src'`,
    `"${prefix}_alt" = ${rolePath}->>'alt'`,
    `"${prefix}_credit" = ${rolePath}->>'credit'`,
    `"${prefix}_source_url" = ${rolePath}->>'sourceUrl'`,
    `"${prefix}_rights_status" = (${rolePath}->'rights'->>'status')::"rights_status"`,
    `"${prefix}_rights_source_type" = (${rolePath}->'rights'->>'sourceType')::"rights_source_type"`,
    `"${prefix}_rights_checked_at" = ${rolePath}->'rights'->>'checkedAt'`,
    `"${prefix}_rights_rights_holder" = ${rolePath}->'rights'->>'rightsHolder'`,
    `"${prefix}_rights_license_url" = ${rolePath}->'rights'->>'licenseUrl'`,
    `"${prefix}_rights_permission_note" = ${rolePath}->'rights'->>'permissionNote'`,
    `"${prefix}_aspect_ratio" = (${rolePath}->>'aspectRatio')::numeric`,
  ];
}

function imageBackfillStatement(spec: ImageBackfillSpec): string {
  const assignments = spec.roles.flatMap((role) => imageAssetBackfillAssignments(spec.jsonColumn, role));
  return `UPDATE "${spec.table}" SET ${assignments.join(', ')} WHERE "${spec.jsonColumn}" IS NOT NULL;`;
}

