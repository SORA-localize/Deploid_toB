/**
 * 手書き追記（自動生成部分ではない）: `images`/`logos`をJSON列から構造化列へ移す際、
 * 自動生成された`up()`は新しい列を追加した直後に旧JSON列を`DROP COLUMN`するだけで、
 * 既存データを新しい列へ複製しない。ロボット画像・メーカーロゴの実データを失わないため、
 * `DROP COLUMN`の直前に、JSONの各roleキー・各サブフィールドを対応する新しい列へ
 * `UPDATE ... SET`でコピーするSQLをここで組み立てる（役割×サブフィールド数が多く手書きだと
 * 転記ミスの危険が大きいため、`ADD COLUMN`と同じ命名規則からプログラムで生成する）。
 */
interface ImageBackfillSpec {
  table: string;
  jsonColumn: string;
  roles: readonly string[];
}

